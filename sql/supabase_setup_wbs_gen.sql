-- ==============================================================
-- WBS 일정 분석 전용 스키마 wbs_gen 생성
-- 새 Supabase 환경의 SQL Editor에서 한 번 실행합니다(데이터는 비어 있는 상태로 생성).
-- 실행 후 Project Settings > Data API의 Exposed schemas에 wbs_gen을 추가합니다.
-- ==============================================================

create schema if not exists wbs_gen;

-- 1. 프로젝트 목록
create table if not exists wbs_gen.wbs_gen_projects (
  id          bigint generated by default as identity primary key,
  created_at  timestamp with time zone default timezone('utc'::text, now()) not null,
  name        text not null,
  description text,
  start_date  date,
  end_date    date
);

-- 2. 프로젝트별 구성원
create table if not exists wbs_gen.wbs_gen_members (
  id          bigint generated by default as identity primary key,
  created_at  timestamp with time zone default timezone('utc'::text, now()) not null,
  project_id  bigint not null references wbs_gen.wbs_gen_projects(id) on delete cascade,
  name        text not null,
  role        text,
  email       text not null,
  phone       text,
  title       text
);
create index if not exists wbs_gen_members_project_id_idx on wbs_gen.wbs_gen_members (project_id);

-- 3. 프로젝트별 WBS 분석 결과
create table if not exists wbs_gen.wbs_gen_analyses (
  id          bigint generated by default as identity primary key,
  saved_at    timestamp with time zone default timezone('utc'::text, now()) not null,
  project_id  bigint not null references wbs_gen.wbs_gen_projects(id) on delete cascade,
  wbs_date    date not null,
  file_name   text not null,
  file_data   text,
  tasks       jsonb not null default '[]'::jsonb,
  summary     jsonb not null default '{}'::jsonb
);
create index if not exists wbs_gen_analyses_project_id_idx on wbs_gen.wbs_gen_analyses (project_id, wbs_date desc);

-- 4. RLS 정책(현재 운영과 같은 공개 정책 — 보안 강화는 개선 권고 #8로 보류 중)
alter table wbs_gen.wbs_gen_projects enable row level security;
alter table wbs_gen.wbs_gen_members  enable row level security;
alter table wbs_gen.wbs_gen_analyses enable row level security;

drop policy if exists "gen projects select" on wbs_gen.wbs_gen_projects;
create policy "gen projects select" on wbs_gen.wbs_gen_projects for select using (true);
drop policy if exists "gen projects insert" on wbs_gen.wbs_gen_projects;
create policy "gen projects insert" on wbs_gen.wbs_gen_projects for insert with check (true);
drop policy if exists "gen projects update" on wbs_gen.wbs_gen_projects;
create policy "gen projects update" on wbs_gen.wbs_gen_projects for update using (true);
drop policy if exists "gen projects delete" on wbs_gen.wbs_gen_projects;
create policy "gen projects delete" on wbs_gen.wbs_gen_projects for delete using (true);

drop policy if exists "gen members select" on wbs_gen.wbs_gen_members;
create policy "gen members select" on wbs_gen.wbs_gen_members for select using (true);
drop policy if exists "gen members insert" on wbs_gen.wbs_gen_members;
create policy "gen members insert" on wbs_gen.wbs_gen_members for insert with check (true);
drop policy if exists "gen members update" on wbs_gen.wbs_gen_members;
create policy "gen members update" on wbs_gen.wbs_gen_members for update using (true);
drop policy if exists "gen members delete" on wbs_gen.wbs_gen_members;
create policy "gen members delete" on wbs_gen.wbs_gen_members for delete using (true);

drop policy if exists "gen analyses select" on wbs_gen.wbs_gen_analyses;
create policy "gen analyses select" on wbs_gen.wbs_gen_analyses for select using (true);
drop policy if exists "gen analyses insert" on wbs_gen.wbs_gen_analyses;
create policy "gen analyses insert" on wbs_gen.wbs_gen_analyses for insert with check (true);
drop policy if exists "gen analyses update" on wbs_gen.wbs_gen_analyses;
create policy "gen analyses update" on wbs_gen.wbs_gen_analyses for update using (true);
drop policy if exists "gen analyses delete" on wbs_gen.wbs_gen_analyses;
create policy "gen analyses delete" on wbs_gen.wbs_gen_analyses for delete using (true);

-- 5. 권한: 이 스키마에만 API 역할(anon·authenticated·service_role) 접근 허용
grant usage on schema wbs_gen to anon, authenticated, service_role;
grant select, insert, update, delete on all tables in schema wbs_gen to anon, authenticated, service_role;
grant usage, select on all sequences in schema wbs_gen to anon, authenticated, service_role;
alter default privileges in schema wbs_gen grant select, insert, update, delete on tables to anon, authenticated, service_role;
alter default privileges in schema wbs_gen grant usage, select on sequences to anon, authenticated, service_role;

-- 6. 확인: 테이블 3개, RLS ON, 정책 4개씩, 행 0건이 나오면 정상
select c.relname as table_name,
       case when c.relrowsecurity then 'ON' else 'OFF' end as rls,
       (select count(*) from pg_policies p where p.schemaname = 'wbs_gen' and p.tablename = c.relname) as policies,
       has_table_privilege('anon', c.oid, 'SELECT') as anon_select
from pg_class c join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'wbs_gen' and c.relkind = 'r'
order by 1;
